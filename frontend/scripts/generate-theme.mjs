import { readFile, writeFile } from 'node:fs/promises'

const themeDir = new URL('../src/theme/', import.meta.url)
const readTokens = async (name) => JSON.parse(await readFile(new URL(`tokens/${name}.json`, themeDir), 'utf8'))
const tokens = {
  ...await readTokens('beeline-carnica-primitives'),
  ...await readTokens('beeline-heroui-semantics'),
}
const flat = new Map()
function flatten(group, path = []) {
  for (const [key, value] of Object.entries(group)) {
    const next = [...path, key]
    if ('$value' in value) flat.set(next.join('.'), value)
    else flatten(value, next)
  }
}
flatten(tokens)

const variable = (path) => path.startsWith('HeroUI.')
  ? `--${path.slice(7)}`
  : `--beeline-${path.slice(11).replaceAll('.', '-')}`

function resolve(path, mode, seen = []) {
  const token = flat.get(path)
  if (!token || seen.includes(path)) throw new Error(`Invalid token reference: ${[...seen, path].join(' → ')}`)
  const value = token.$extensions?.mode?.[mode] ?? token.$value
  const reference = /^\{(.+)\}$/.exec(value)
  if (reference) {
    resolve(reference[1], mode, [...seen, path])
    return `var(${variable(reference[1])})`
  }
  if (token.$type !== 'color' || !/^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) {
    throw new Error(`Unsupported color: ${path}`)
  }
  return value
}

const declarations = (prefix, mode) => [...flat.keys()]
  .filter((path) => path.startsWith(prefix))
  .map((path) => `    ${variable(path)}: ${resolve(path, mode)};`).join('\n')

const css = `/* Generated by npm run theme:generate. Edit the source JSON tokens. */
@layer base {
  :root, :host {
${declarations('Primitives.', 'light')}
    --white: var(--beeline-white);
    --black: var(--beeline-black);
    --snow: var(--beeline-snow);
    --eclipse: var(--beeline-eclipse);
  }

  :root, .light, .default, [data-theme="light"], [data-theme="default"] {
    color-scheme: light;
${declarations('HeroUI.', 'light')}
  }

  .dark, [data-theme="dark"] {
    color-scheme: dark;
${declarations('HeroUI.', 'dark')}
  }
}
`
await writeFile(new URL('beeline.css', themeDir), css)
console.log(`Generated Beeline theme: ${Object.keys(tokens.HeroUI).length} semantic colors, light + dark.`)
